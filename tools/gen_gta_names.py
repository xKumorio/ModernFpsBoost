# Generates src/profilers/gta_names_gen.h: every gta_sa.exe 1.0 US function gta-reversed names, sorted by
# address, for the spike profiler's stack samples.
#   py -3 gen_gta_names.py <gta-reversed/source> <out.h>
import sys
from gen_samp_timers import gta_names


def main():
    src, out = sys.argv[1:3]
    names = gta_names(src)
    rows = sorted((a, n) for a, n in names.items() if 0x401000 <= a < 0x857000)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// ModernFpsBoost - Copyright (c) 2026 Softik Inquisitor (https://vk.ru/miurawr). All rights reserved.\n')
        f.write('// Copying, redistribution or reuse of this file without the author\'s permission is prohibited.\n')
        f.write('// Generated by tools/gen_gta_names.py from gta-reversed - do not edit.\n#pragma once\n\n')
        f.write('struct GtaName { DWORD addr; const char *name; };\nstatic const GtaName kGtaNames[] = {\n')
        for a, n in rows:
            f.write('\t{ 0x%06X, "%s" },\n' % (a, n.replace('"', '')))
        f.write('};\n')
    print(len(rows), 'names')


main()
