"""Generates src/profilers/samp_timers_versions_gen.h: the SampProfiler timers of samp_timers_gen.h
(made from R1) for every SA-MP version.

Each timed samp function is ported with sampport.py. Its timed call sites are the calls of it inside
the same caller function: the caller is ported too and, when the target has as many calls of the
function inside it as R1, they are taken in order. Anything that does not port is left out (0);
the profiler re-checks every site (E8 + expected target) before patching anyway.

Usage: python gen_samp_timers_versions.py <ref/samp dir> ../src/profilers/samp_timers_gen.h ../src/profilers/samp_timers_versions_gen.h
"""
import os
import re
import sys

from sampport import VERSIONS, Porter, Samp


def read_r1(path):
    s = open(path, encoding='utf-8').read()
    funcs_block = s[s.index('kSampTimerFuncs[] = {'):s.index('};', s.index('kSampTimerFuncs[] = {'))]
    funcs = [(int(a, 16), int(g)) for a, g in re.findall(r'\{ 0x([0-9A-F]+), ".*?", (\d), -?\d+ \}', funcs_block)]
    sites_block = s[s.index('kSampTimerSites[] = {'):s.index('};', s.index('kSampTimerSites[] = {'))]
    sites = [(int(a, 16), int(f), int(g)) for a, f, g in re.findall(r'\{ 0x([0-9A-F]+), (\d+), (\d) \}', sites_block)]
    return funcs, sites


def main():
    ref, r1h, out = sys.argv[1:4]
    funcs, sites = read_r1(r1h)
    r1 = Samp(os.path.join(ref, 'R1', 'samp.dll'))
    func_rva = {}
    site_at = {}
    for v in VERSIONS:
        d = Samp(os.path.join(ref, v, 'samp.dll'))
        p = Porter(r1, d) if v != 'R1' else None
        fr = []
        for rva, gta in funcs:
            if gta or v == 'R1':
                fr.append(rva)
            else:
                t = p.func(rva)
                fr.append(t or 0)
        func_rva[v] = fr
        sa = []
        group_cache = {}
        for at, fi, gta in sites:
            if gta or v == 'R1':
                sa.append(at)
                continue
            f_r1, f_v = funcs[fi][0], fr[fi]
            caller = r1.func_of(at)
            if not f_v or caller is None:
                sa.append(0)
                continue
            key = (caller, f_r1)
            if key not in group_cache:
                c_v = p.func(caller)
                mine = [a for a in r1.calls_to(f_r1) if caller <= a < r1.func_end(caller, cap=0x10000)]
                theirs = [a for a in d.calls_to(f_v) if c_v is not None and c_v <= a < d.func_end(c_v, cap=0x10000)]
                group_cache[key] = dict(zip(mine, theirs)) if len(mine) == len(theirs) else {}
            sa.append(group_cache[key].get(at, 0))
        site_at[v] = sa
        print(v, 'functions %d/%d, sites %d/%d' % (sum(1 for x in fr if x), len(fr), sum(1 for x in sa if x), len(sa)))

    L = ['// ModernFpsBoost - Copyright (c) 2026 Softik Inquisitor (https://vk.ru/miurawr). All rights reserved.', "// Copying, redistribution or reuse of this file without the author's permission is prohibited.", '// Generated by tools/gen_samp_timers_versions.py - do not edit.',
         '// kSampTimerFuncs / kSampTimerSites (samp_timers_gen.h, R1) for every version: rva or 0 when not found.',
         '#pragma once', '',
         'static const DWORD kSampTimerFuncRva[SAMP_VERSIONS][%d] = {' % len(funcs)]
    for v in VERSIONS:
        L.append('\t{ // ' + v)
        for k in range(0, len(funcs), 12):
            L.append('\t\t' + ' '.join('0x%X,' % x for x in func_rva[v][k:k + 12]))
        L.append('\t},')
    L += ['};', '', 'static const DWORD kSampTimerSiteAt[SAMP_VERSIONS][%d] = {' % len(sites)]
    for v in VERSIONS:
        L.append('\t{ // ' + v)
        for k in range(0, len(sites), 12):
            L.append('\t\t' + ' '.join('0x%X,' % x for x in site_at[v][k:k + 12]))
        L.append('\t},')
    L += ['};', '']
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))


if __name__ == '__main__':
    main()
