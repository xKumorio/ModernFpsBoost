"""Generates src/ui/icons.h: UTF-8 strings of the Lucide icons the menu uses + the glyph ranges to load.

Usage: python gen_icons.py <lucide-static>/font/codepoints.json ../src/ui/icons.h
Add a name to ICONS and re-run to use another icon (https://lucide.dev/icons).
"""
import json
import sys

ICONS = '''
zap braces car users scroll-text settings x type box person-standing arrow-down-to-line link footprints
eye-off grid-3x3 calculator bone scan-eye building-2 repeat search shield-off tag plug-zap layers
message-square-text glasses signpost volume-2 cloud-moon circle-check circle-alert circle-pause clock
play copy folder-open file-cog keyboard info cpu activity sun-moon monitor layout-grid gauge heart
sparkles chevron-right timer rocket cuboid puzzle
chevron-down chevrons-up-down chevrons-down-up pause clipboard-copy list-tree hash map code file-code
'''.split()

codepoints = json.load(open(sys.argv[1], encoding='utf-8'))
lines = ['// ModernFpsBoost - Copyright (c) 2026 Softik Inquisitor (https://vk.ru/miurawr). All rights reserved.', "// Copying, redistribution or reuse of this file without the author's permission is prohibited.", '// Generated by tools/gen_icons.py from lucide-static font/codepoints.json - do not edit.',
         '// Lucide icons (ISC license, third_party/lucide/LICENSE.txt), font: third_party/lucide/lucide.ttf.',
         '#pragma once', '']
cps = []
for name in ICONS:
    cp = codepoints[name]
    cps.append(cp)
    utf8 = ''.join('\\x%02x' % b for b in chr(cp).encode('utf-8'))
    lines.append('#define ICON_%s "%s"' % (name.upper().replace('-', '_'), utf8))
lines += ['', '// pairs of [first, last] codepoints for ImGui, 0-terminated', 'static const unsigned short kIconRanges[] = {']
for cp in sorted(set(cps)):
    lines.append('\t0x%04X, 0x%04X,' % (cp, cp))
lines += ['\t0,', '};', '']
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(cps), 'icons')
