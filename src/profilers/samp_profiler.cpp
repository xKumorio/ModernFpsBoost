const char *SampProfilerTimerLabel(int i) { return i >= 0 && i < kSampTimers ? TimerLabel(i) : ""; }

const char *SampProfilerNameOf(DWORD pc, DWORD *off)
{
	if (!g_samp || g_sampVersion < 0 || pc < (DWORD)g_samp) return nullptr;
	DWORD rva = pc - (DWORD)g_samp;
	if (rva < 0x1000 || rva >= 0x400000) return nullptr;
	int best = -1;
	DWORD bestRva = 0;
	for (int i = 0; i < kSampFuncs; i++) {
		if (kSampTimerFuncs[i].gta) continue;
		DWORD a = TimerAddr(i);
		if (a <= rva && a >= bestRva) best = i, bestRva = a;
	}
	if (best < 0 || rva - bestRva >= 0x1000) return nullptr; // far below: most likely another function
	*off = rva - bestRva;
	return TimerLabel(best);
}
