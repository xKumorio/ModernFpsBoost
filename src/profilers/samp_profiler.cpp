// [SampProfiler] time spent in samp.dll 0.3.7 R1 functions (and GTA frame stages / entity virtuals).
//
// Function bodies are left alone (SAMPFUNCS and others hook them and jump back into their first
// bytes). Instead every direct call to a timed function listed in samp_timers_gen.h is pointed at a
// stub that records the time and swaps the return address for ReturnThunk, so the exit is timed too
// without touching the arguments or the calling convention (variadic ScriptCommand included).
// A call site is patched only if it still is E8 to the expected function, so this runs after every
// fix that redirects calls. Only the game's main thread is timed. Frames that an exception skipped
// are dropped by comparing stack addresses. Sites are written while the main thread is suspended
// outside the patched bytes.
// Report: ModernFpsBoost_samp.log every interval seconds, with the fixes' stats.
// samp_timers_gen.h is generated by tools/gen_samp_timers.py.

#include <algorithm>

